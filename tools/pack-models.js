// Packs assets/models/*.glb into assets/models.js (one base64 string per model), which is what the game
// loads: a single script works from file:// and inside a one-file build, where fetching .glb files would not.
// Run after adding, removing or replacing a model:  node tools/pack-models.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'models'), out = {};
for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.glb')).sort()) out[path.basename(f, '.glb')] = fs.readFileSync(path.join(dir, f)).toString('base64');
const js = '// Generated by tools/pack-models.js from assets/models/*.glb. CC0 models, see CREDITS.md. Each value is a base64 GLB.\nconst MODEL_B64 = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(dir, '..', 'models.js'), js);
console.log(Object.keys(out).length + ' models, ' + Math.round(js.length / 1024) + ' KB');
